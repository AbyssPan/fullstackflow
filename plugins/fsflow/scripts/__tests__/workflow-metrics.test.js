#!/usr/bin/env node
const assert = require('assert/strict')
const fs = require('fs')
const os = require('os')
const path = require('path')
const { spawnSync } = require('child_process')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'fsflow-metrics-'))
process.env.CODEBUDDY_PROJECT_DIR = root
process.env.CLAUDE_PROJECT_DIR = root
const state = require('../lib/state')
const { collectMetrics, normalizeUsage, formatMetrics, saveMetrics } = require('../services/workflow-metrics')
const id = 'METRICS'
const dir = path.join(state.PLANS_DIR, id)
fs.mkdirSync(dir, { recursive: true })
const start = Date.parse('2026-09-30T00:00:00Z')
const ts = ms => new Date(start + ms).toISOString()
const events = []
const add = (ms, e) => events.push({ ts: ts(ms), storyId: id, ...e })
const transition = (ms, fromPhase, toPhase) => add(ms, { type: 'phase_transition', result: 'transitioned', details: { fromPhase, toPhase } })
const spawn = (ms, invocationId) => add(ms, { type: 'agent_spawn', phase: 2, agent: 'developer', invocationId })
const result = (ms, invocationId, usage) => add(ms, { type: 'agent_result', phase: 2, agent: 'developer', invocationId, result: 'completed', details: { usage } })
try {
  state.writeStateFile(id, { storyId: id, phase: 3, status: 'running', createdAt: ts(0), phases: {} })
  transition(1000, 0, 1)
  transition(2000, 1, 2)
  spawn(2500, 'a')
  spawn(2700, 'b')
  result(4300, 'b', { total_tokens: 200, input_tokens: 150, output_tokens: 50 })
  result(4500, 'a', { totalTokens: 1000 })
  result(4500, 'a', { totalTokens: 1000 }) // callback replay
  transition(5000, 2, 3)
  transition(6000, 3, 2)
  add(6000, { type: 'fix_loop', from: '3', sourcePhase: '3' })
  spawn(6000, 'retry')
  result(8000, 'retry', null)
  transition(8000, 2, 3)
  fs.writeFileSync(path.join(dir, 'trace.jsonl'), events.map(e => JSON.stringify(e)).join('\n') + '\n{incomplete')
  const metrics = collectMetrics(id, start + 10000)
  assert.equal(metrics.totals.elapsedMs, 10000)
  assert.equal(metrics.phases[2].elapsedMs, 5000, 'all visits count')
  assert.equal(metrics.phases[2].agentMs, 5600, 'parallel agent work is additive, not phase wall time')
  assert.equal(metrics.phases[2].attempts, 3)
  assert.equal(metrics.totals.reportedTokens, 1200, 'duplicate callback counted once')
  assert.equal(metrics.totals.reportedInvocations, 2)
  assert.equal(metrics.totals.missingInvocations, 1)
  assert.equal(metrics.phases[0].tokens.total, null, 'missing tokens must not become zero')
  assert.equal(metrics.phases[3].recoveries, 1)
  assert.ok(formatMetrics(metrics).includes('1200（部分）'))
  assert.equal(normalizeUsage({ total_tokens: -1 }), null)
  assert.equal(normalizeUsage({ total_tokens: '100' }), null)
  assert.equal(normalizeUsage({ input_tokens: 100, output_tokens: 30 }).totalTokens, null, 'do not infer host billing totals')
  assert.equal(normalizeUsage({ total_tokens: 0 }).totalTokens, 0)
  assert.equal(normalizeUsage({ input_tokens_details: { cached_tokens: 20 } }).cacheReadTokens, 20)
  // Real hook invocation: host fields optional; command always allows execution.
  const hook = (mode, event) => {
    const r = spawnSync(process.execPath, [path.join(__dirname, '../hooks/trace-agent.js'), mode], { input: JSON.stringify(event), encoding: 'utf8' })
    assert.equal(r.status, 0, r.stderr)
    assert.equal(JSON.parse(r.stdout).continue, true)
  }
  fs.writeFileSync(path.join(state.PLANS_DIR, '.harness-active'), JSON.stringify({ active: true, storyId: id }))
  const event = { tool_name: 'Agent', tool_use_id: 'hook-1', tool_input: { subagent_type: 'reviewer', model: 'configured-model' } }
  hook('start', event)
  hook('result', { ...event, tool_response: { model: 'actual-model-v2', usage: { total_tokens: 42, input_tokens: 30, output_tokens: 12, cache_read_input_tokens: 10 }, duration_ms: 25 } })
  hook('result', { ...event, tool_response: { usage: { total_tokens: 42 }, duration_ms: 25 } })
  assert.equal(collectMetrics(id).phases[3].tokens.total, 42)
  assert.equal(collectMetrics(id).phases[3].agentMs, 25)
  assert.deepEqual(collectMetrics(id).phases[3].models, ['actual-model-v2'])
  assert.deepEqual(collectMetrics(id).phases[3].configuredModels, ['configured-model'])
  assert.equal(collectMetrics(id).phases[3].tokens.cacheRead, 10)
  assert.equal(collectMetrics(id).calls.find(c => c.invocationId === 'hook-1').modelSource, 'host')
  assert.ok(fs.existsSync(path.join(dir, 'workflow-metrics.json')), 'agent hook persists report beside Story artifacts')
  assert.ok(fs.readFileSync(path.join(dir, 'workflow-metrics.md'), 'utf8').includes('actual-model-v2'))
  const unknown = { ...event, tool_use_id: 'hook-2' }
  hook('start', unknown)
  hook('result', { ...unknown, tool_response: { text: 'no usage available' } })
  assert.equal(collectMetrics(id).phases[3].tokens.missingInvocations, 1)
  assert.equal(collectMetrics(id).calls.find(c => c.invocationId === 'hook-2').model, null, 'configuration must not impersonate actual model')
  hook('result', { ...unknown, tool_response: { model: 'later-model', usage: { total_tokens: 7 } } })
  assert.equal(collectMetrics(id).phases[3].tokens.total, 49, 'later evidence enriches the same invocation once')
  assert.equal(collectMetrics(id).phases[3].attempts, 2)
  const background = { ...event, tool_use_id: 'background', tool_input: { subagent_type: 'reviewer', run_in_background: true } }
  hook('start', background)
  hook('result', { ...background, tool_response: { is_async: true, usage: { total_tokens: 9999 } } })
  assert.equal(collectMetrics(id).phases[3].tokens.total, 49, 'background launch is not completion')
  const cli = spawnSync(process.execPath, [path.join(__dirname, '../commands/workflow-metrics.js'), id, '--json'], { encoding: 'utf8' })
  assert.equal(cli.status, 0)
  assert.equal(JSON.parse(cli.stdout).phases.length, 8)
  const persisted = saveMetrics(id)
  const saved = JSON.parse(fs.readFileSync(persisted.json, 'utf8'))
  assert.equal(saved.schemaVersion, 1)
  assert.equal(saved.calls.length, collectMetrics(id).calls.length)
  assert.ok(fs.readFileSync(persisted.markdown, 'utf8').includes('缓存读取'))
  assert.equal(fs.readdirSync(dir).some(f => f.endsWith('.tmp')), false)
  const snapshot = fs.readFileSync(persisted.json, 'utf8')
  require('../commands/dispatch').dispatch(id)
  assert.equal(fs.readFileSync(persisted.json, 'utf8'), snapshot, 'dispatch remains read-only even with persistent reports')
  console.log('per-stage timing, retries, parallelism, usage coverage, deduplication and hook telemetry passed')
} finally { fs.rmSync(root, { recursive: true, force: true }) }
